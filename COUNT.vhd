LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.STD_LOGIC_UNSIGNED.ALL;
USE IEEE.STD_LOGIC_ARITH.ALL;

ENTITY COUNT  IS
	PORT( EN, RSET, CLK : IN STD_LOGIC;
			SP1, SP2, SP3, SP4 : IN STD_LOGIC;  --10 30 60 90
			H1, H2 : IN STD_LOGIC_VECTOR(3 DOWNTO 0);
			A1, A2 : IN STD_LOGIC;
			SUM_REST : IN STD_LOGIC;
			
			RES0, RES1, RES2, RES3 : OUT STD_LOGIC_VECTOR(3 DOWNTO 0);

			DIS0, DIS1, DIS2, DIS3 : OUT STD_LOGIC_VECTOR(3 DOWNTO 0);
			SUM : OUT STD_LOGIC_VECTOR(15 DOWNTO 0)
			);
END COUNT;

ARCHITECTURE BHV OF COUNT IS

SIGNAL DIS : INTEGER RANGE 0 TO 300000 := 0;

SIGNAL CNT : INTEGER RANGE 0 TO 999999999 := 0;
SIGNAL QIBU : INTEGER RANGE 0 TO 999999999 := 0;
SIGNAL TEMP : INTEGER RANGE 0 TO 9999 := 0;

BEGIN

PROCESS(EN, CLK)
BEGIN

IF RSET = '1' THEN
	DIS <= 0;
	CNT <= 0;
	IF A1 = '1' THEN
		IF A2 = '1' THEN
			QIBU <= 2600000;
		ELSE
			QIBU <= 1600000;
		END IF;
	ELSE
		IF A2 = '1' THEN
			QIBU <= 2400000;
		ELSE
			QIBU <= 1400000;
		END IF;
	END IF;
ELSIF EN = '1' THEN
	IF CLK'EVENT AND CLK = '1' THEN 
		IF SP2 = '1' THEN DIS <= DIS + 500;
		ELSIF SP3 = '1' THEN DIS <= DIS + 1000;
		ELSIF SP4 = '1' THEN DIS <= DIS + 1500;
		ELSE DIS <= DIS + 375;
		END IF;
	
		IF (H1 = "0010" and H2 = "0011") OR (H1 = "0000" and H2 < 5) THEN
			IF DIS <= 3000 THEN
				CNT <= QIBU;
			ELSIF DIS <= 15000 THEN
				IF SP2 = '1' THEN CNT <= CNT + (500 * 351);
				ELSIF SP3 = '1' THEN CNT <= CNT + (1000 * 351);
				ELSIF SP4 = '1' THEN CNT <= CNT + (1500 * 351);
				ELSE CNT <= CNT + (375 * 351);
				END IF;
			ELSE
				IF SP2 = '1' THEN CNT <= CNT + (500 * 526);
				ELSIF SP3 = '1' THEN CNT <= CNT + (1000 * 526);
				ELSIF SP4 = '1' THEN CNT <= CNT + (1500 * 526);
				ELSE CNT <= CNT + (375 * 526);
				END IF;
			END IF;
		ELSE
			IF DIS <= 3000 THEN
				CNT <= QIBU;
			ELSIF DIS <= 15000 THEN
				IF SP2 = '1' THEN CNT <= CNT + (500 * 270);
				ELSIF SP3 = '1' THEN CNT <= CNT + (1000 * 270);
				ELSIF SP4 = '1' THEN CNT <= CNT + (1500 * 270);
				ELSE CNT <= CNT + (375 * 270);
				END IF;
			ELSE
				IF SP2 = '1' THEN CNT <= CNT + (500 * 405);
				ELSIF SP3 = '1' THEN CNT <= CNT + (1000 * 405);
				ELSIF SP4 = '1' THEN CNT <= CNT + (1500 * 405);
				ELSE CNT <= CNT + (375 * 407);
				END IF;
			END IF;
		END IF;
		RES0 <= CONV_STD_LOGIC_VECTOR(CNT / 10000 REM 10, 4);
		RES1 <= CONV_STD_LOGIC_VECTOR(CNT / 100000 REM 10, 4);
		RES2 <= CONV_STD_LOGIC_VECTOR(CNT / 1000000 REM 10, 4);
		RES3 <= CONV_STD_LOGIC_VECTOR(CNT / 10000000 REM 10, 4);
		
		DIS0 <= CONV_STD_LOGIC_VECTOR(DIS / 100 REM 10, 4);
		DIS1 <= CONV_STD_LOGIC_VECTOR(DIS / 1000 REM 10, 4);
		DIS2 <= CONV_STD_LOGIC_VECTOR(DIS / 10000 REM 10, 4);
		DIS3 <= CONV_STD_LOGIC_VECTOR(DIS / 100000 REM 10, 4);
		
		
	END IF;
END IF;

END PROCESS;

REG:PROCESS(EN)
BEGIN
IF SUM_REST = '1' THEN
	TEMP <= 0;
ELSE
	IF EN'EVENT AND EN = '0' THEN
		TEMP <= TEMP + CNT;
	END IF;
END IF;

SUM <= CONV_STD_LOGIC_VECTOR(TEMP / 1000 REM 10, 4) & CONV_STD_LOGIC_VECTOR(TEMP / 100 REM 10, 4) & CONV_STD_LOGIC_VECTOR(TEMP / 10 REM 10, 4) & CONV_STD_LOGIC_VECTOR(TEMP REM 10, 4);

END PROCESS;

END BHV;
