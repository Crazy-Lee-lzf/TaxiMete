LIBRARY IEEE;
USE IEEE.STD_LOGIC_1164.ALL;
USE IEEE.STD_LOGIC_UNSIGNED.ALL;

ENTITY SWT IS
	PORT( EN, CIN: IN STD_LOGIC;
			CT0, CT1: OUT STD_LOGIC
			);
END SWT;

ARCHITECTURE BHV OF SWT IS
BEGIN
PROCESS(EN, CIN)
BEGIN
IF EN = '1' THEN
	IF CIN = '0' THEN
		CT0 <= '1';
		CT1 <= '0';
	ELSIF CIN = '1' THEN
		CT0 <= '0';
		CT1 <= '1';
	END IF;
ELSE
	CT0 <= '0';
	CT1 <= '0';
END IF;
END PROCESS;

END BHV;